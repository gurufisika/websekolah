-- 1. TABEL GURU & TENAGA PENDIDIK
create table if not exists public.guru (
  id bigint generated by default as identity primary key,
  nip text,
  nama text not null,
  jk text,
  ttl text,
  mapel text not null,
  jabatan text not null,
  status text not null default 'PNS',
  pendidikan text,
  nohp text,
  email text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Pastikan seluruh kolom tersedia jika tabel guru sudah ada sebelumnya
alter table public.guru add column if not exists nip text;
alter table public.guru add column if not exists nama text;
alter table public.guru add column if not exists jk text;
alter table public.guru add column if not exists ttl text;
alter table public.guru add column if not exists mapel text;
alter table public.guru add column if not exists jabatan text;
alter table public.guru add column if not exists status text default 'PNS';
alter table public.guru add column if not exists pendidikan text;
alter table public.guru add column if not exists nohp text;
alter table public.guru add column if not exists email text;
alter table public.guru add column if not exists created_at timestamp with time zone default timezone('utc'::text, now());

-- 2. TABEL SISWA / PESERTA DIDIK
create table if not exists public.siswa (
  id bigint generated by default as identity primary key,
  nis text not null,
  nama text not null,
  jk text not null,
  ttl text,
  kelas text not null,
  jurusan text not null,
  agama text,
  wali text,
  nohp text,
  status text not null default 'Aktif',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. KEAMANAN & KEBIJAKAN AKSES (ROW LEVEL SECURITY)
alter table public.guru enable row level security;
alter table public.siswa enable row level security;

-- Hapus kebijakan lama jika ada agar tidak bentrok
drop policy if exists "Akses penuh guru" on public.guru;
drop policy if exists "Akses penuh siswa" on public.siswa;

-- Berikan akses penuh (SELECT, INSERT, UPDATE, DELETE) agar Dashboard Admin dapat mengelola data secara real-time
create policy "Akses penuh guru" on public.guru
  for all using (true) with check (true);

create policy "Akses penuh siswa" on public.siswa
  for all using (true) with check (true);

-- 4. AKTIFKAN REPLIKASI REALTIME SUPABASE (Opsional tapi disarankan agar perubahan langsung muncul tanpa reload)
alter publication supabase_realtime add table public.guru;
alter publication supabase_realtime add table public.siswa;

