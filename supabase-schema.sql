-- 1. TABEL BERITA & ARTIKEL
create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Akademik',
  author text not null default 'Tim Humas',
  date text not null,
  image text not null,
  summary text not null,
  content text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. TABEL PENGUMUMAN
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  priority text not null default 'UMUM',
  category text not null default 'Akademik',
  status_text text not null default 'Terkini',
  badge_color text not null default 'bg-blue-50 text-blue-700 border-blue-200',
  date text not null,
  description text not null,
  details text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. TABEL GALERI FOTO
create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'kegiatan',
  category_label text not null default 'Kegiatan Siswa',
  image text not null,
  description text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. TABEL PESAN KONTAK MASUK
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_name text not null,
  sender_email text not null,
  sender_subject text not null,
  sender_message text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ====================================================================
-- KEAMANAN: ROW LEVEL SECURITY (RLS)
-- ====================================================================

-- Aktifkan RLS di setiap tabel
alter table public.articles enable row level security;
alter table public.announcements enable row level security;
alter table public.gallery enable row level security;
alter table public.messages enable row level security;

-- Kebijakan Akses: Publik dapat MEMBACA Berita, Pengumuman, dan Galeri
create policy "Publik dapat melihat berita" on public.articles
  for select using (true);

create policy "Publik dapat melihat pengumuman" on public.announcements
  for select using (true);

create policy "Publik dapat melihat galeri" on public.gallery
  for select using (true);

-- Kebijakan Akses: Publik dapat MENGIRIM formulir pesan kontak
create policy "Publik dapat mengirim pesan kontak" on public.messages
  for insert with check (true);

-- Kebijakan Akses: Admin yang sudah terautentikasi (login) memiliki AKSES PENUH (CRUD)
create policy "Admin dapat mengelola berita" on public.articles
  for all using (auth.role() = 'authenticated');

create policy "Admin dapat mengelola pengumuman" on public.announcements
  for all using (auth.role() = 'authenticated');

create policy "Admin dapat mengelola galeri" on public.gallery
  for all using (auth.role() = 'authenticated');

create policy "Admin dapat melihat dan menghapus pesan" on public.messages
  for all using (auth.role() = 'authenticated');


